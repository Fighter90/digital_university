// DIG-33 — «Время везде одинаковое и в поясе пользователя».
//
// Боль из аудита: время создания в «Задачах» и «Заявках» расходилось
// (форматтер брал часовой пояс сервера). Контракт: у заявок ОДИН
// форматтер с ЯВНОЙ зоной Europe/Moscow (пояс пользователя прототипа,
// конвенция проекта: schedule-time.ts, PDF-документы, MCP) и суффиксом
// «МСК» — сервер и клиент рендерят одинаково на любой машине.
import { describe, expect, it } from 'vitest';

import { formatRequestDate } from '@/lib/request-labels';
import { formatReadyBy } from '@/lib/request-sla';

// 16 ноября 2026, 07:05 UTC = 10:05 МСК (в любом поясе машины).
const AT_1005_MSK = new Date('2026-11-16T07:05:00.000Z');

describe('formatRequestDate: одна зона Europe/Moscow + суффикс «МСК»', () => {
  it('рендерит московское время независимо от пояса машины', () => {
    // Суффикс «МСК» ломает старую реализацию при ЛЮБОМ host-поясе
    // (красная фаза), а точные «10:05» ловят протечку пояса сервера
    // (UTC-сервер дал бы «07:05», американский — «02:05»).
    expect(formatRequestDate(AT_1005_MSK)).toBe('16 ноября в 10:05 МСК');
  });

  it('один и тот же момент даёт одну метку для списка, карточки и событий', () => {
    // Список (requests-screen), шапка карточки и таймлайн событий
    // вызывают один и тот же форматтер — строки обязаны совпадать байт в байт.
    const a = formatRequestDate(AT_1005_MSK);
    const b = formatRequestDate(new Date(AT_1005_MSK.getTime()));
    expect(a).toBe(b);
  });

  it('полночь МСК не уезжает на предыдущий день', () => {
    // 15 ноября 21:30 UTC = 16 ноября 00:30 МСК.
    expect(formatRequestDate(new Date('2026-11-15T21:30:00.000Z'))).toBe('16 ноября в 00:30 МСК');
  });
});

describe('formatReadyBy: дата готовности тоже в Москве', () => {
  it('граница суток считается по Москве', () => {
    // 14 ноября 21:30 UTC = 15 ноября 00:30 МСК.
    expect(formatReadyBy(new Date('2026-11-14T21:30:00.000Z'))).toBe('15 ноября');
  });
});
