// DIG-27 — векторный шрифт выписки PDF (5×8, глифы — заполненные
// прямоугольники).
//
// В PDF нет стандартного шрифта с кириллицей, а вкладывать TTF в
// прототип нельзя (лицензии и вес). Поэтому текст выписки рисуется
// глифами 5×8: каждая строка глифа — горизонтальные отрезки («runs»),
// которые PDF-писатель печатает операторами `re f`. Такой документ
// открывается в любом просмотрщике, ничего не подгружает и полностью
// детерминирован. Тот же писатель переиспользует DIG-47 (справка + QR).
//
// Сетка: ширина глифа 5 px, высота 8 px (строки 0–7), базовая линия —
// строка 6, строка 7 — выносной элемент (р, у, ф, д, Д, Ц, Щ), строки 0–1 —
// надстрочные знаки (Ё, Й, ё, й). Покрытие: кириллица (верхний и нижний
// регистры), латиница, цифры, пунктуация, пробел. Проверяется тестом
// tests/transcript-pdf.test.ts («каждый символ строк выписки покрыт»).

