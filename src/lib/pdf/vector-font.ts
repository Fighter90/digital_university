/** Строки глифа (битовые маски 5 px) или null, если глифа нет. */
export function glyphRows(ch: string): readonly number[] | null {
  return GLYPHS[ch] ?? null;
}

/** Есть ли глиф для символа (тесты проверяют покрытие текста выписки). */
export function hasGlyphFor(ch: string): boolean {
  return ch in GLYPHS;
}

/** Ширина текста в пикселях шрифта (без последнего межбуквенного зазора). */
export function textWidthPx(text: string): number {
  if (text.length === 0) return 0;
  return text.length * GLYPH_ADVANCE - (GLYPH_ADVANCE - GLYPH_WIDTH);
}
